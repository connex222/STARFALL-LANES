'use strict';
const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const load = require('./load-server');
const app = load(0xFACE2026), I = app._internal;
after(() => app.cleanup());
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
function makeBots(n=2) {
  const room=I.makeRoom();room.mode='quick';
  room.players=Array.from({length:n},(_,i)=>({id:'bot'+i,token:'test-private-token-'+i,name:'Tester '+i,avatar:i,isAI:true,bot:true,ws:null}));
  room.hostId='bot0';
  return room;
}
const controller = (room, pid) => ({room,role:'phone',pid,readyState:1,send() {}});
test('host alone can opt in before match; default is off; neither can change it mid-game', async () => {
  const room=makeBots();assert.equal(room.playtestEnabled,false);
  I.onMessage(controller(room,'bot1'),{t:'playtestToggle',enabled:true});assert.equal(room.playtestEnabled,false);
  I.onMessage(controller(room,'bot0'),{t:'playtestToggle',enabled:'true'});assert.equal(room.playtestEnabled,false);
  I.onMessage(controller(room,'bot0'),{t:'playtestToggle',enabled:true});assert.equal(room.playtestEnabled,true);
  I.startGame(room);
  I.onMessage(controller(room,'bot0'),{t:'playtestToggle',enabled:false});assert.equal(room.playtestEnabled,true);
  const began=Date.now();while(room.game.phase!=='over'&&Date.now()-began<20000) await sleep(10);
  assert.equal(room.game.phase,'over','bot match timed out');
  const report=room.game.playtestReport;
  assert.ok(report && report.json && report.markdown);
  const data=report.json;
  assert.equal(data.schema,'starfall.playtest.v1');
  assert.equal(data.session.playerCount,2);
  assert.equal(data.session.mode,'quick');
  assert.equal(data.session.map,'small');
  assert.equal(data.session.players.length,2);
  assert.ok(data.rounds.length>0);
  assert.ok(data.phases.some(p=>p.phase==='plan'));
  assert.ok(data.phases.some(p=>p.phase==='reveal'));
  assert.ok(data.phases.every(p=>Number.isInteger(p.durationMs) && p.durationMs>=0));
  assert.ok(data.commands.length>0);
  assert.ok(data.commands.every(c=>['success','failed'].includes(c.result)));
  assert.equal(data.summary.totalCommands,data.commands.length);
  assert.equal(data.summary.failedCommands,data.commands.filter(c=>c.result==='failed').length);
  assert.equal(data.summary.tradeOffersProposed,data.trades.filter(x=>x.kind==='offer_proposed').length);
  assert.equal(data.summary.tradeOffersAccepted,data.trades.filter(x=>x.kind==='offer_resolved'&&x.status==='accepted').length);
  assert.deepEqual(Array.from(data.winners),Array.from(room.game.results.winners));
  assert.deepEqual(Array.from(data.finalScores.map(x=>x.final)),Array.from(room.game.results.rows.map(x=>x.final)));
  assert.match(report.markdown,/Average round/);
  assert.match(report.markdown,/Influence by round/);
  assert.match(report.markdown,/Failed commands by player and round/);
  assert.match(report.markdown,/Final scores/);
  assert.ok(!JSON.stringify(data).includes('test-private-token'), 'must not leak seat tokens');
  const pub=I.pubState(room);
  assert.equal(pub.game.playtest.enabled,true);
  assert.equal(pub.game.playtest.report,report);
  assert.ok(data.rounds.every(r=>Number.isInteger(r.durationMs)&&r.durationMs>=0));
  assert.ok(!Object.hasOwn(data,'_phaseOpen'));
  room.game.alive=false;app.rooms.delete(room.code);
}, { timeout:30000 });
test('disabled Playtest Mode does not store reports or send game telemetry', () => {
  const room=makeBots();I.startGame(room);
  assert.equal(room.game.playtest,null);
  assert.equal(I.pubState(room).game.playtest.enabled,false);
  I.endGame(room);
  assert.equal(room.game.playtestReport,undefined);
  assert.equal(I.pubState(room).game.playtest.report,null);
  room.game.alive=false;app.rooms.delete(room.code);
});
